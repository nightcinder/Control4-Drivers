-- Self-test: proves clock, timers, UpdateProperty logging and error capture.
local sim = require("c4sim")
local t = require("t")
local C4 = sim.C4

t.test("clock advances", function()
  sim.reset()
  t.eq(sim.now(), 0, "start")
  sim.advance(1500)
  t.eq(sim.now(), 1500, "after advance")
end)

t.test("one-shot timer fires once at due time", function()
  sim.reset()
  local n = 0
  C4:SetTimer(1000, function() n = n + 1 end)
  sim.advance(999)
  t.eq(n, 0, "before due")
  sim.advance(1)
  t.eq(n, 1, "at due")
  sim.advance(5000)
  t.eq(n, 1, "not repeated")
end)

t.test("repeating timer re-arms and Cancel stops it", function()
  sim.reset()
  local n = 0
  local tm = C4:SetTimer(1000, function() n = n + 1 end, true)
  sim.advance(3500)
  t.eq(n, 3, "three firings")
  tm:Cancel()
  sim.advance(5000)
  t.eq(n, 3, "cancelled")
end)

t.test("timers fire in time order with clock set to due time", function()
  sim.reset()
  local order, at = {}, {}
  C4:SetTimer(300, function() order[#order + 1] = "b"; at.b = sim.now() end)
  C4:SetTimer(100, function() order[#order + 1] = "a"; at.a = sim.now() end)
  sim.advance(500)
  t.eq(table.concat(order, ","), "a,b", "order")
  t.eq(at.a, 100, "a time")
  t.eq(at.b, 300, "b time")
end)

t.test("UpdateProperty sets value and logs it", function()
  sim.reset()
  C4:UpdateProperty("Status", "up")
  t.eq(Properties.Status, "up", "value")
  t.eq(sim.props[#sim.props].name, "Status", "log name")
  t.eq(sim.props[#sim.props].value, "up", "log value")
end)

t.test("direct Properties assignment is recorded", function()
  sim.reset()
  Properties.Direct = 1
  t.ok(sim.props_direct.Direct == true, "recorded")
  t.ok(not sim.props_api.Direct, "not via API")
end)

t.test("error in callback is captured, advance continues", function()
  sim.reset()
  local after = false
  C4:SetTimer(10, function() error("boom") end)
  C4:SetTimer(20, function() after = true end)
  sim.advance(30)
  t.eq(#sim.errors, 1, "one error")
  t.ok(sim.errors[1]:find("boom", 1, true) ~= nil, "message kept")
  t.ok(after, "later timer still ran")
end)

t.test("unstubbed C4 call is a warning, not a crash", function()
  sim.reset()
  local r = C4:NoSuchThingXyz()
  t.eq(r, nil, "returns nil")
  t.eq(sim.warnings[1], "unstubbed C4:NoSuchThingXyz", "warning text")
end)

t.test("SendToDevice recorded and queryable", function()
  sim.reset()
  C4:SendToDevice(5, "ON", {})
  t.eq(sim.last_sent("ON").id, 5, "id")
  t.eq(sim.count_sent("ON"), 1, "count")
end)

t.test("set_var is returned by GetDeviceVariable", function()
  sim.reset()
  sim.set_var(7, 3, "on")
  t.eq(C4:GetDeviceVariable(7, 3), "on", "value")
end)

t.test("load_driver runs init, property callbacks and xml defaults", function()
  sim.reset()
  local lua = os.tmpname()
  local xml = os.tmpname()
  local f = assert(io.open(lua, "w"))
  f:write("function OnDriverInit() C4:UpdateProperty('Status', 'init') end\n")
  f:write("function OnPropertyChanged(n) C4:UpdateProperty('Last', n) end\n")
  f:close()
  f = assert(io.open(xml, "w"))
  f:write("<devicedata><properties><property><name>Host</name><default>10.0.0.1</default></property></properties></devicedata>\n")
  f:close()
  local good = sim.load_driver(lua, { xml = xml })
  os.remove(lua)
  os.remove(xml)
  t.ok(good, "no errors: " .. tostring(sim.errors[1]))
  t.eq(Properties.Host, "10.0.0.1", "xml default")
  t.eq(Properties.Status, "init", "OnDriverInit ran")
  t.eq(Properties.Last, "Host", "OnPropertyChanged ran")
end)

t.finish("selftest")
